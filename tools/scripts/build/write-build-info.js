import { writeFile } from "fs/promises";
import { dirname, join, resolve } from "path";
import { fileURLToPath } from "url";

const now = new Date();
const centralParts = new Intl.DateTimeFormat("en-US", {
  timeZone: "America/Chicago",
  year: "numeric",
  month: "2-digit",
  day: "2-digit",
  hour: "2-digit",
  minute: "2-digit",
  second: "2-digit",
  hourCycle: "h23",
  timeZoneName: "short",
}).formatToParts(now);
const getPart = (type) =>
  centralParts.find((part) => part.type === type)?.value ?? "";
const buildStamp = `${getPart("year")}-${getPart("month")}-${getPart("day")} ${getPart("hour")}:${getPart("minute")}:${getPart("second")} ${getPart("timeZoneName")}`;
const projectRoot = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../../..",
);
const outputPath = join(projectRoot, "src", "extension", "buildInfo.ts");

const fileContent = `// AUTO-GENERATED FILE - DO NOT EDIT\n// Regenerated by tools/scripts/build/write-build-info.js during the extension build.\nexport const BUILD_STAMP = "${buildStamp}";\n`;

await writeFile(outputPath, fileContent, "utf8");
console.log(`Wrote build stamp: ${buildStamp}`);
