import { mkdir, writeFile } from "fs/promises";
import { dirname, join, resolve } from "path";
import { fileURLToPath } from "url";
import { computeBuildStamp } from "./build-stamp.mjs";

const buildStamp = computeBuildStamp();
const projectRoot = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../../..",
);
const outputPath = join(projectRoot, "src", "buildInfo.ts");
const stampPath = join(projectRoot, "dist", "build-stamp.txt");

const fileContent = `// AUTO-GENERATED FILE - DO NOT EDIT\n// Regenerated by tools/scripts/build/write-build-info.js during the extension build.\nexport const BUILD_STAMP = "${buildStamp}";\n`;

await mkdir(dirname(stampPath), { recursive: true });
await writeFile(outputPath, fileContent, "utf8");
await writeFile(stampPath, buildStamp, "utf8");
console.log(`Wrote build stamp: ${buildStamp}`);
